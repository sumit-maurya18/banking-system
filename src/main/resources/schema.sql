
-- 1. USERS
-- Stores authentication credentials and user roles.
-- Admin users do not require a customer profile.

CREATE TABLE users (
                       user_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                       email VARCHAR(150) NOT NULL UNIQUE,
                       password_hash VARCHAR(255) NOT NULL,

                       role VARCHAR(20) NOT NULL
                           CHECK (role IN ('CUSTOMER', 'ADMIN')),

                       status VARCHAR(20) NOT NULL
                           CHECK (status IN ('ACTIVE', 'INACTIVE', 'BLOCKED')),

                       created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                       updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
                   );

-- 2. CUSTOMERS
-- Stores customer profile information.
-- Each customer is associated with exactly one user.

CREATE TABLE customers (
                           customer_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                           user_id BIGINT NOT NULL UNIQUE,
                           full_name VARCHAR(100) NOT NULL,
                           phone_number VARCHAR(15) NOT NULL UNIQUE,

                           created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                           updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

                           CONSTRAINT fk_customers_user
                               FOREIGN KEY (user_id)
                                   REFERENCES users(user_id)
                                   ON DELETE RESTRICT
                       );

-- 3. ACCOUNTS
-- Stores bank accounts and their current balances.
-- Version supports optimistic locking through JPA @Version.

CREATE TABLE accounts (
                          account_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                          account_number VARCHAR(20) NOT NULL UNIQUE,
                          customer_id BIGINT NOT NULL,

                          account_type VARCHAR(20) NOT NULL
                              CHECK (account_type IN ('SAVINGS', 'CURRENT')),

                          balance NUMERIC(19,2) NOT NULL DEFAULT 0
                              CHECK (balance >= 0),

                          status VARCHAR(20) NOT NULL
                              CHECK (status IN ('ACTIVE', 'INACTIVE', 'FROZEN', 'CLOSED')),

                          version BIGINT NOT NULL DEFAULT 0,

                          created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                          updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

                          CONSTRAINT fk_accounts_customer
                              FOREIGN KEY (customer_id)
                                  REFERENCES customers(customer_id)
                                  ON DELETE RESTRICT
                      );

-- 4. TRANSACTIONS
-- Stores deposit, withdrawal and transfer records.
-- transaction_id is the unique external transaction identifier.

CREATE TABLE transactions (
                              id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                              transaction_id VARCHAR(50) NOT NULL UNIQUE,

                              source_account_id BIGINT,
                              destination_account_id BIGINT,

                              transaction_type VARCHAR(20) NOT NULL
                                  CHECK (
                                      transaction_type IN ('DEPOSIT', 'WITHDRAWAL', 'TRANSFER')
                                      ),

                              amount NUMERIC(19,2) NOT NULL
                                  CHECK (amount > 0),

                              status VARCHAR(20) NOT NULL
                                  CHECK (status IN ('PENDING', 'SUCCESS', 'FAILED', 'REJECTED')),

                              created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                              completed_at TIMESTAMPTZ,

                              CONSTRAINT fk_transactions_source_account
                                  FOREIGN KEY (source_account_id)
                                      REFERENCES accounts(account_id)
                                      ON DELETE RESTRICT,

                              CONSTRAINT fk_transactions_destination_account
                                  FOREIGN KEY (destination_account_id)
                                      REFERENCES accounts(account_id)
                                      ON DELETE RESTRICT,

                              CONSTRAINT chk_transaction_account_structure
                                  CHECK (
                                      (
                                          transaction_type = 'DEPOSIT'
                                              AND source_account_id IS NULL
                                              AND destination_account_id IS NOT NULL
                                          )
                                          OR
                                      (
                                          transaction_type = 'WITHDRAWAL'
                                              AND source_account_id IS NOT NULL
                                              AND destination_account_id IS NULL
                                          )
                                          OR
                                      (
                                          transaction_type = 'TRANSFER'
                                              AND source_account_id IS NOT NULL
                                              AND destination_account_id IS NOT NULL
                                              AND source_account_id <> destination_account_id
                                          )
                                      )
                          );


-- 5. TRANSACTION_AUDIT
-- Stores the lifecycle and execution history of transactions.
-- One transaction can have multiple audit records.

CREATE TABLE transaction_audit (
                                   audit_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                                   transaction_record_id BIGINT NOT NULL,

                                   event_type VARCHAR(50) NOT NULL,
                                   thread_name VARCHAR(100),
                                   operation VARCHAR(100) NOT NULL,
                                   result VARCHAR(20) NOT NULL,

                                   duration_ms BIGINT
                                       CHECK (duration_ms >= 0),

                                   message VARCHAR(255),

                                   created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

                                   CONSTRAINT fk_audit_transaction
                                       FOREIGN KEY (transaction_record_id)
                                           REFERENCES transactions(id)
                                           ON DELETE RESTRICT
                               );


-- 6. FAILED_TRANSACTIONS
-- Stores detailed failure information.
-- A transaction can have at most one failure record.

CREATE TABLE failed_transactions (
                                     failure_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                                     transaction_record_id BIGINT NOT NULL UNIQUE,

                                     error_category VARCHAR(50) NOT NULL,
                                     failure_reason VARCHAR(255) NOT NULL,
                                     failure_stage VARCHAR(50) NOT NULL,

                                     created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

                                     CONSTRAINT fk_failed_transaction
                                         FOREIGN KEY (transaction_record_id)
                                             REFERENCES transactions(id)
                                             ON DELETE RESTRICT
                                 );

-- 7. SECURITY_EVENTS
-- Stores login, logout and unauthorized-access events.
-- user_id is nullable for unauthenticated or unknown users.

CREATE TABLE security_events (
                                 event_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                                 user_id BIGINT,

                                 event_type VARCHAR(30) NOT NULL
                                     CHECK (
                                         event_type IN (
                                                        'LOGIN',
                                                        'LOGOUT',
                                                        'UNAUTHORIZED_ACCESS'
                                             )
                                         ),

                                 outcome VARCHAR(20) NOT NULL
                                     CHECK (outcome IN ('SUCCESS', 'FAILURE')),

                                 ip_address VARCHAR(45),
                                 description VARCHAR(255),

                                 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

                                 CONSTRAINT fk_security_events_user
                                     FOREIGN KEY (user_id)
                                         REFERENCES users(user_id)
                                         ON DELETE RESTRICT
                             );

-- INDEXES
-- Primary keys and UNIQUE constraints already create indexes.
-- These indexes support frequently used application queries.

-- Find accounts belonging to a customer.
CREATE INDEX idx_accounts_customer_id
    ON accounts(customer_id);

-- Find transactions initiated from an account.
CREATE INDEX idx_transactions_source_created
    ON transactions(source_account_id, created_at);

-- Find transactions received by an account.
CREATE INDEX idx_transactions_destination_created
    ON transactions(destination_account_id, created_at);

-- Filter transactions by status and date.
CREATE INDEX idx_transactions_status_created
    ON transactions(status, created_at);

-- Retrieve audit history for a transaction.
CREATE INDEX idx_transaction_audit_record_created
    ON transaction_audit(transaction_record_id, created_at);

-- Retrieve security events associated with a user.
CREATE INDEX idx_security_events_user_created
    ON security_events(user_id, created_at);